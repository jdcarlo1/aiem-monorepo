@dataclass(frozen=True)
class StrategySpec:
    name:           str
    family:         str
    aliases:        tuple = field(default_factory=tuple)
    risk_class:     str   = RISK_DEFINED
    execution_mode: str   = MODE_AUTONOMOUS
    direction:      str   = ANY
    vol_thesis:     str   = VOL_ANY
    min_legs:       int   = 1
    max_legs:       int   = 4
    has_stock:      bool  = False
    # leg_templates: list of dicts {asset_type, side, delta_target, dte_slot, offset, ratio}
    leg_templates:  tuple = field(default_factory=tuple)
    min_dte:        int   = 2
    max_dte:        int   = 730
    notes:          str   = ""

def _lt(asset_type, side, delta=0.50, slot="FRONT", offset=0, ratio=1):
    return {"asset_type": asset_type, "side": side, "delta_target": delta,
            "dte_slot": slot, "strike_offset": offset, "ratio": ratio}

def _call(side, delta=0.50, slot="FRONT", offset=0, ratio=1):
    return _lt(ASSET_CALL, side, delta, slot, offset, ratio)

def _put(side, delta=0.50, slot="FRONT", offset=0, ratio=1):
    return _lt(ASSET_PUT, side, delta, slot, offset, ratio)

def _stock(side, ratio=1):
    return _lt(ASSET_STOCK, side, 0, "FRONT", 0, ratio)

