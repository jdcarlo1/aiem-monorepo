# ── Lookup indices ───────────────────────────────────────────────────────────
CATALOG_BY_NAME: dict[str, StrategySpec] = {s.name: s for s in CATALOG}

CATALOG_BY_FAMILY: dict[str, list[StrategySpec]] = {}
for _s in CATALOG:
    CATALOG_BY_FAMILY.setdefault(_s.family, []).append(_s)

AUTONOMOUS_STRATEGIES = [s for s in CATALOG if s.execution_mode == MODE_AUTONOMOUS]
ANALYSIS_ONLY_STRATEGIES = [s for s in CATALOG if s.execution_mode == MODE_ANALYSIS_ONLY]

# Build alias lookup
CATALOG_BY_ALIAS: dict[str, StrategySpec] = {}
for _s in CATALOG:
    CATALOG_BY_ALIAS[_s.name.lower()] = _s
    for _a in _s.aliases:
        CATALOG_BY_ALIAS[_a.lower()] = _s


def lookup(name: str) -> Optional[StrategySpec]:
    """Case-insensitive lookup by name or alias."""
    return CATALOG_BY_ALIAS.get(name.lower())


def families() -> list[str]:
    return sorted(CATALOG_BY_FAMILY.keys())


def count() -> dict:
    return {
        "total":          len(CATALOG),
        "autonomous":     len(AUTONOMOUS_STRATEGIES),
        "analysis_only":  len(ANALYSIS_ONLY_STRATEGIES),
        "by_family":      {f: len(s) for f, s in CATALOG_BY_FAMILY.items()},
    }
